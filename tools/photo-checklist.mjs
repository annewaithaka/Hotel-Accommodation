/**
 * Generates the photo handover checklist from the built pages.
 *
 *   node tools/photo-checklist.mjs          → assets/images/PHOTO-CHECKLIST.md
 *   node tools/photo-checklist.mjs --csv    → also assets/images/photo-shot-list.csv
 *
 * It reads every page, pulls each .photo slot out of the markup, checks whether
 * the file is on disk, and groups the result by property. Re-run it after any
 * page change so the checklist stays truthful.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "assets/images");

const PAGE_TITLES = {
  "index.html": "Home",
  "properties.html": "Properties",
  "malewa.html": "Malewa",
  "stay.html": "Stay",
  "dining.html": "Dining",
  "conferences.html": "Conferences",
  "team-building.html": "Team building",
  "experiences.html": "Experiences",
  "clavina.html": "Clavina",
  "clavina-pax.html": "Clavina Pax",
  "gallery.html": "Gallery",
  "about.html": "About",
  "contact.html": "Contact",
  "book.html": "Enquiry",
  "404.html": "404",
};

const GROUP_LABELS = {
  malewa: "Malewa Riverside Resort & Cottages",
  clavina: "Clavina",
  "clavina-pax": "Clavina Pax",
  branding: "Branding",
};

/* How each layout wrapper displays the photograph. */
const RATIO_GUIDE = {
  "photo--cover": { label: "Full-bleed hero", size: "2400 × 1600 px or larger" },
  "photo--landscape": { label: "Landscape 3:2", size: "1600 × 1200 px" },
  "photo--wide": { label: "Wide 16:9", size: "1600 × 900 px" },
  "photo--tall": { label: "Portrait 3:4", size: "1200 × 1600 px" },
  "photo--portrait": { label: "Portrait 4:5", size: "1200 × 1500 px" },
  "photo--square": { label: "Square 1:1", size: "1200 × 1200 px" },
};

const ratioFor = (classes) => {
  const key = Object.keys(RATIO_GUIDE).find((token) => classes.includes(token));
  return key ? RATIO_GUIDE[key] : { label: "Landscape", size: "1600 × 1200 px" };
};

const propertyFor = (src) => {
  const parts = src.split("/");
  const index = parts.indexOf("images");
  return index >= 0 ? parts[index + 1] : "other";
};

const fileFor = (src) => src.replace(/^assets\/images\//, "");

/* --- Collect every slot -------------------------------------------- */

const SLOT_PATTERN =
  /<(?:figure|div) class="photo([^"]*)" data-slot="([^"]*)">\s*<img src="([^"]+)" alt="([^"]*)"/g;

const slots = new Map();

for (const page of readdirSync(ROOT).filter((f) => f.endsWith(".html")).sort()) {
  const html = readFileSync(join(ROOT, page), "utf8");
  for (const match of html.matchAll(SLOT_PATTERN)) {
    const [, classes, slot, src, alt] = match;
    if (!slots.has(src)) {
      slots.set(src, {
        src,
        file: fileFor(src),
        property: propertyFor(src),
        slot,
        alt,
        ratio: ratioFor(classes),
        pages: new Set(),
      });
    }
    slots.get(src).pages.add(PAGE_TITLES[page] || page);
  }
}

const rows = [...slots.values()].map((row) => ({
  ...row,
  pages: [...row.pages].sort(),
  exists: existsSync(join(ROOT, row.src)),
}));

/* --- Group by property, keeping folder order ----------------------- */

const byProperty = new Map();
for (const row of rows) {
  if (!byProperty.has(row.property)) byProperty.set(row.property, []);
  byProperty.get(row.property).push(row);
}

for (const list of byProperty.values()) {
  list.sort((a, b) => a.file.localeCompare(b.file));
}

const order = ["malewa", "clavina", "clavina-pax", "branding", "other"];
const properties = [...byProperty.keys()].sort(
  (a, b) => order.indexOf(a) - order.indexOf(b)
);

/* --- Write the checklist -------------------------------------------- */

const total = rows.length;
const present = rows.filter((row) => row.exists).length;

const lines = [
  "# Photo checklist",

  "",

  "Generated from the built pages by `node tools/photo-checklist.mjs`.",
  "Do not edit this file by hand — re-run the command instead.",

  "",

  `**${present} of ${total} photographs are in place.** Each row below is one`,
  "photograph on the site. Tick the box when the file is sitting at that exact",
  "path with that exact name.",

  "",

  "Filenames are **case-sensitive on the web**. `Malewa-Hero.JPG` and",
  "`malewa-hero.jpg` are two different files as far as the browser is",
  "concerned — keep everything lowercase, with hyphens and no spaces.",

  "",
  "---",
  "",
];

for (const property of properties) {
  const list = byProperty.get(property);
  const done = list.filter((row) => row.exists).length;

  lines.push(`## ${GROUP_LABELS[property] || property}`);
  lines.push("");
  lines.push(`${done} of ${list.length} in place.`);
  lines.push("");
  lines.push("| Done | File to add under `assets/images/` | What it should show | Best size | Appears on |");
  lines.push("|---|---|---|---|---|");

  for (const row of list) {
    const box = row.exists ? "[x]" : "[ ]";
    // Where the alt text is still a placeholder, the slot name reads better as
    // the description of what the photograph should show.
    const described = row.alt.includes("to be supplied") ? row.slot : row.alt;
    const subject = described.replace(/\|/g, "/");
    const pages = row.pages.slice(0, 4).join(", ") + (row.pages.length > 4 ? "…" : "");
    lines.push(
      `| ${box} | \`${row.file}\` | ${subject} | ${row.ratio.size} | ${pages} |`
    );
  }

  lines.push("");
}

lines.push("---");
lines.push("");
lines.push("## Also needed for social sharing");
lines.push("");
lines.push(
  "| Done | File | What it should show | Best size |",
  "|---|---|---|---|",
  `| ${existsSync(join(OUT_DIR, "branding/malewa-riverside-social.jpg")) ? "[x]" : "[ ]"} | \`branding/malewa-riverside-social.jpg\` | The image that appears when a page is shared on WhatsApp, Facebook or X | 1200 × 630 px |`
);
lines.push("");
lines.push(
  "When every box above is ticked, run `node tools/check-site.mjs` — it should",
  "report zero photography slots outstanding."
);
lines.push("");

writeFileSync(join(OUT_DIR, "PHOTO-CHECKLIST.md"), lines.join("\n"), "utf8");
console.log(`  assets/images/PHOTO-CHECKLIST.md — ${present}/${total} in place`);

/* --- Optional CSV shot list ------------------------------------------ */

if (process.argv.includes("--csv")) {
  const escape = (value) => `"${String(value).replace(/"/g, '""')}"`;
  const csv = [
    ["Property", "File to add under assets/images/", "What it should show", "Best size", "Appears on", "Status"]
      .map(escape)
      .join(","),
    ...rows
      .sort(
        (a, b) =>
          order.indexOf(a.property) - order.indexOf(b.property) ||
          a.file.localeCompare(b.file)
      )
      .map((row) =>
        [
          GROUP_LABELS[row.property] || row.property,
          row.file,
          row.alt,
          row.ratio.size,
          row.pages.join(" / "),
          row.exists ? "supplied" : "needed",
        ]
          .map(escape)
          .join(",")
      ),
  ].join("\n");

  writeFileSync(join(OUT_DIR, "photo-shot-list.csv"), csv, "utf8");
  console.log("  assets/images/photo-shot-list.csv");
}
